const ubootDir = "../../../os/bootloader/uboot"

// ubootKeysHeader is soundtap-keys.h for keys: each non-empty key as its 32 raw bytes, in
// order, as Verify uses them. An empty one, the reserve before it exists, is left out, as
// Verify skips it.
func ubootKeysHeader(keys []string) ([]byte, error) {
	names := []string{"PublicKey", "ReservePublicKey"}
	var b bytes.Buffer
	b.WriteString("/* Generated by app/internal/release/uboot_test.go from release.PublicKeys(); regenerate\n")
	b.WriteString(" * it with UPDATE_UBOOT_KEYS=1 go test -run TestUbootKeys ./internal/release. The keys the\n")
	b.WriteString(" * USB-stick recovery verifies Update.stu.sig with (ADR 0048); an empty one is left out. */\n")
	b.WriteString("static const unsigned char st_release_keys[][32] = {\n")
	n := 0
	for i, k := range keys {
		k = strings.TrimSpace(k)
		if k == "" {
			continue
		}
		pub, err := base64.StdEncoding.Strict().DecodeString(k)
		if err != nil || len(pub) != ed25519.PublicKeySize {
			return nil, fmt.Errorf("key %d is not an ed25519 public key", i)
		}
		name := fmt.Sprintf("key %d", i)
		if i < len(names) {
			name = names[i]
		}
		fmt.Fprintf(&b, "\t/* %s %s */\n\t{", name, k)
		for j, c := range pub {
			if j%8 == 0 {
				b.WriteString("\n\t\t")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "0x%02x,", c)
		}
		b.WriteString("\n\t},\n")
		n++
	}
	if n == 0 {
		return nil, fmt.Errorf("no release public key")
	}
	b.WriteString("};\n")
	return b.Bytes(), nil
}

// U-Boot trusts exactly the keys soundtapd does, so a rotation (RELEASING.md, "Release
// keys") that changes release.go and forgets the bootloader fails here.
func TestUbootKeysAreTheReleaseKeys(t *testing.T) {
	path := filepath.Join(ubootDir, "soundtap-keys.h")
	want, err := ubootKeysHeader(PublicKeys())
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("UPDATE_UBOOT_KEYS") == "1" {
		if err := os.WriteFile(path, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is not release.PublicKeys(); regenerate it with UPDATE_UBOOT_KEYS=1", path)
	}
	// The reserve placeholder is left out rather than compiled in as zeroes, which would
	// be a small-order point some forged signatures verify against.
	two, err := ubootKeysHeader([]string{PublicKey, PublicKey})
	if err != nil || bytes.Count(two, []byte("\t{")) != 2 {
		t.Fatalf("two keys: %v\n%s", err, two)
	}
	if one, _ := ubootKeysHeader([]string{PublicKey, " "}); bytes.Count(one, []byte("\t{")) != 1 {
		t.Fatalf("an empty reserve was compiled in:\n%s", one)
	}
}

// The harness reads one case per line and answers with one line:
//
//	verify <kind> <keys> <text>                          -> ok <kind> <profile> <version> <sha256> | err <n>
//	stick <image profile> <keys> <text> <sha256> [owner] -> ok | err <n>
//	ownerkey <value>                                     -> ok <hex key> | err
//
// keys is a comma-separated list of hex public keys, text the .sig file in hex ("-" for an
// empty one). stick runs what the recovery runs: st_trusted_keys over the keys and the
// owner key from the environment, st_verify for core, st_stick_policy, st_matches. owner
// and value are the environment's soundtap_owner_key in hex: "-" when it is not set, "e"
// when it is set empty. ownerkey is st_owner_key alone.
const ubootHarness = `
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "soundtap-sig.h"

void randombytes(unsigned char *x, unsigned long long n) { (void)x; (void)n; abort(); }

static size_t unhex(const char *s, unsigned char *out, size_t max)
{
	size_t n = 0;
	unsigned int b;

	if (!strcmp(s, "-"))
		return 0;
	while (s[0] && s[1] && n < max && sscanf(s, "%2x", &b) == 1) {
		out[n++] = b;
		s += 2;
	}
	if (*s)
		abort();
	return n;
}

static int keys(char *list, unsigned char (*out)[32])
{
	int n = 0;
	char *k;

	for (k = strtok(list, ","); k; k = strtok(NULL, ","))
		if (unhex(k, out[n++], 32) != 32)
			abort();
	return n;
}

/* An environment value in the harness's spelling: "-" unset, "e" empty, otherwise hex. */
static const char *envvalue(const char *s, char *buf, size_t max)
{
	size_t n;

	if (!strcmp(s, "-"))
		return NULL;
	if (!strcmp(s, "e"))
		return "";
	n = unhex(s, (unsigned char *)buf, max - 1);
	buf[n] = 0;
	return buf;
}

int main(void)
{
	static char line[16384];
	unsigned char key[4][32], all[5][32], text[4096], digest[32];
	struct st_statement st;
	char op[16], arg[256], list[1024], hextext[8192], hexdigest[80], ownerhex[256], owner[128];
	size_t len;
	int n, r, i;

	while (fgets(line, sizeof(line), stdin)) {
		n = sscanf(line, "%15s %255s %1023s %8191s %79s %255s", op, arg, list, hextext, hexdigest, ownerhex);
		if (!strcmp(op, "ownerkey") && n == 2) {
			if (st_owner_key(envvalue(arg, owner, sizeof(owner)), key[0])) {
				printf("err\n");
			} else {
				printf("ok ");
				for (i = 0; i < 32; i++)
					printf("%02x", key[0][i]);
				printf("\n");
			}
			fflush(stdout);
			continue;
		}
		if (n < 4)
			abort();
		len = unhex(hextext, text, sizeof(text));
		if (!strcmp(op, "verify") && n == 4) {
			r = st_verify((const char *)text, len, (const unsigned char (*)[32])key,
				      keys(list, key), arg, &st);
			if (r) {
				printf("err %d\n", r);
				continue;
			}
			printf("ok %s %s %s ", st.kind, st.profile, st.version);
			for (i = 0; i < 32; i++)
				printf("%02x", st.digest[i]);
			printf("\n");
		} else if (!strcmp(op, "stick") && (n == 5 || n == 6)) {
			int nrelease = keys(list, key);
			const char *env = n == 6 ? envvalue(ownerhex, owner, sizeof(owner)) : NULL;
			int nkeys = st_trusted_keys((const unsigned char (*)[32])key, nrelease, env, all);

			r = st_verify((const char *)text, len, (const unsigned char (*)[32])all,
				      nkeys, "core", &st);
			if (!r)
				r = st_stick_policy(&st, arg);
			if (!r && unhex(hexdigest, digest, 32) == 32)
				r = st_matches(&st, digest);
			if (r)
				printf("err %d\n", r);
			else
				printf("ok\n");
		} else {
			abort();
		}
		fflush(stdout);
	}
	return 0;
}
`

// The codes soundtap-sig.h returns.
const (
	stNotStatement = "err 1"
	stBadEncoding  = "err 2"
	stBadSignature = "err 3"
	stWrongKind    = "err 4"
	stWrongProfile = "err 5"
	stStock        = "err 6"
	stWrongFile    = "err 7"
)

// buildUbootVerifier compiles soundtap-sig.c and tweetnacl.c, unchanged, with the harness.
// Sanitizers catch a parser that reads past a mutated statement; a compiler without them
// still builds the plain harness.
func buildUbootVerifier(t *testing.T) string {
	t.Helper()
	cc, err := exec.LookPath("cc")
	if err != nil {
		t.Skip("needs a C compiler")
	}
	dir := t.TempDir()
	harness := filepath.Join(dir, "harness.c")
	if err := os.WriteFile(harness, []byte(ubootHarness), 0o644); err != nil {
		t.Fatal(err)
	}
	bin := filepath.Join(dir, "verifier")
	build := func(extra ...string) error {
		// tweetnacl.c is upstream's file as it is (ADR 0124); its warnings are not ours, and
		// it shifts negative limbs left, which GCC defines (as U-Boot builds it) and
		// UBSan's shift check reports. The rest of UBSan and ASan still watch it.
		nacl := filepath.Join(dir, "tweetnacl.o")
		naclExtra := extra
		if len(extra) > 0 {
			naclExtra = append(append([]string{}, extra...), "-fno-sanitize=shift")
		}
		args := append([]string{"-std=c99", "-O2", "-w", "-c", "-o", nacl, filepath.Join(ubootDir, "tweetnacl.c")}, naclExtra...)
		if out, err := exec.Command(cc, args...).CombinedOutput(); err != nil {
			return fmt.Errorf("%v: %s", err, out)
		}
		args = append([]string{"-std=c99", "-O2", "-Wall", "-Wextra", "-Werror", "-I", ubootDir, "-o", bin,
			harness, filepath.Join(ubootDir, "soundtap-sig.c"), nacl}, extra...)
		if out, err := exec.Command(cc, args...).CombinedOutput(); err != nil {
			return fmt.Errorf("%v: %s", err, out)
		}
		return nil
	}
	if err := build("-fsanitize=address,undefined", "-fno-sanitize-recover=all"); err != nil {
		t.Logf("without sanitizers: %v", err)
		if err := build(); err != nil {
			t.Fatal(err)
		}
	}
	return bin
}

// runUboot feeds the cases to the harness and returns its answers in order.
func runUboot(t *testing.T, bin string, cases []string) []string {
	t.Helper()
	cmd := exec.Command(bin)
	cmd.Stdin = strings.NewReader(strings.Join(cases, "\n") + "\n")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("harness: %v: %s", err, stderr.String())
	}
	var got []string
	sc := bufio.NewScanner(bytes.NewReader(out))
	for sc.Scan() {
		got = append(got, sc.Text())
	}
	if len(got) != len(cases) {
		t.Fatalf("harness answered %d of %d cases: %s", len(got), len(cases), stderr.String())
	}
	return got
}

func hexKeys(t *testing.T, keys ...string) string {
	t.Helper()
	var out []string
	for _, k := range keys {
		pub, err := base64.StdEncoding.DecodeString(k)
		if err != nil {
			t.Fatal(err)
		}
		out = append(out, hex.EncodeToString(pub))
	}
	return strings.Join(out, ",")
}

func hexText(s string) string {
	if s == "" {
		return "-"
	}
	return hex.EncodeToString([]byte(s))
}

// goVerdict is what the harness must answer for a verify case.
func goVerdict(keys []string, text, kind string) string {
	s, err := Verify(keys, text, kind)
	if err != nil {
		return "err"
	}
	return fmt.Sprintf("ok %s %s %s %s", s.Kind, s.Profile, s.Version, hex.EncodeToString(s.Digest))
}

// nonCanonicalS returns sig with S replaced by S+L: the same point, a second encoding that
// TweetNaCl alone would take and crypto/ed25519 refuses.
func nonCanonicalS(t *testing.T, line string) string {
	t.Helper()
	text, b64, _ := strings.Cut(line, " sig=")
	sig, err := base64.StdEncoding.DecodeString(b64)
	if err != nil {
		t.Fatal(err)
	}
	le := func(b []byte) *big.Int {
		r := make([]byte, len(b))
		for i := range b {
			r[len(b)-1-i] = b[i]
		}
		return new(big.Int).SetBytes(r)
	}
	l, _ := new(big.Int).SetString("7237005577332262213973186563042994240857116359379907606001950938285454250989", 10)
	s := new(big.Int).Add(le(sig[32:]), l)
	be := s.FillBytes(make([]byte, 32))
	for i := range 32 {
		sig[32+i] = be[31-i]
	}
	return text + " sig=" + base64.StdEncoding.EncodeToString(sig)
}

// Go and U-Boot read every statement alike: the ones Go signs for each kind, profile and
// version, the one sign.sh wrote, and every statement one edit away from a good one.
// Anything Verify refuses, the stick refuses; anything it accepts, the stick reads as the
// same kind, profile, version and digest.
func TestUbootVerifierMatchesVerify(t *testing.T) {
	bin := buildUbootVerifier(t)
	active, activePriv := testKey(t)
	reserve, reservePriv := testKey(t)
	_, strangerPriv := testKey(t)
	keys := []string{active, reserve}
	file := sha256.Sum256([]byte("Update.stu"))

	var texts []string
	for _, kind := range []string{KindCore, KindApp} {
		for _, profile := range []string{ProfileProduction, ProfileAlpha} {
			for _, version := range []string{"0.1.0", "0.0.1", "10.20.30", "123456789.0.999999999", StockVersion,
				"0.1.0-alpha.1", "0.1.0-alpha.10", "123456789.123456789.123456789-alpha.999999999"} {
				s := Statement{Kind: kind, Profile: profile, Version: version, Digest: file[:]}
				if line, err := Sign(activePriv, s); err == nil {
					texts = append(texts, line+"\n")
				}
			}
		}
	}
	good := mustSign(t, activePriv, Statement{Kind: KindCore, Profile: ProfileProduction, Version: "0.1.0", Digest: file[:]})
	for _, priv := range []ed25519.PrivateKey{reservePriv, strangerPriv} {
		texts = append(texts, mustSign(t, priv, Statement{Kind: KindCore, Profile: ProfileProduction, Version: "0.1.0", Digest: file[:]}))
	}
	texts = append(texts, good, good+"\r\n", nonCanonicalS(t, good), good+"\r", good+"\n\n", good+"\r\r\n", good+"\n\r", good+" ",
		good+"\t", "", "\n", good+"\n"+strings.Repeat(" ", SigMax-len(good)), good+strings.Repeat("\n", SigMax))
	// The four bits after the signature's last byte must be zero (Strict).
	b64 := good[strings.Index(good, " sig=")+5:]
	last := strings.IndexByte("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/", b64[85])
	texts = append(texts, good[:len(good)-3]+string("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"[last|1])+"==")
	var cases, want []string
	for _, text := range texts {
		for _, kind := range []string{KindCore, KindApp} {
			cases = append(cases, fmt.Sprintf("verify %s %s %s", kind, hexKeys(t, keys...), hexText(text)))
			want = append(want, goVerdict(keys, text, kind))
		}
	}
	// Every statement one replaced, deleted or doubled byte away, for the stick's kind and
	// the active key alone: an edit that still parses costs a full ed25519 check per key.
	// The alpha's edits reach every rule of its suffix.
	alpha := mustSign(t, activePriv, Statement{Kind: KindCore, Profile: ProfileProduction, Version: "0.1.0-alpha.1", Digest: file[:]})
	for _, good := range []string{good, alpha} {
		for i := range len(good) {
			edits := []string{good[:i] + good[i+1:], good[:i+1] + good[i:]}
			for _, c := range []byte{' ', '\n', '\r', '\t', 0, '0', '=', '.', '-', good[i] ^ 0x20} {
				edits = append(edits, good[:i]+string([]byte{c})+good[i+1:])
			}
			for _, text := range edits {
				cases = append(cases, fmt.Sprintf("verify core %s %s", hexKeys(t, active), hexText(text)))
				want = append(want, goVerdict([]string{active}, text, KindCore))
			}
		}
	}
	// The sign.sh statement of TestSignShOutputVerifies, signed by openssl.
	const signShKey = "syQ3h0YimtK+yq+OpfGB57V0VvhVdnEpQBwqALv1OUw="
	const signSh = "soundtap-package v1 kind=core profile=production version=0.3.0 " +
		"sha256=a2beb50bfd5a837f9e0970359b42e4da8b8d465e9f33eb7e3a4989f6f2c9afc1 " +
		"sig=ukF0FTJvfHvlULoQ5vQv5Nnt859WzGwhunqfaTcItnGMQhw2InFc652NSe/3BpeNbjaRKgNCcSgQY/96d2mMAQ==\n"
	cases = append(cases, fmt.Sprintf("verify core %s %s", hexKeys(t, signShKey), hexText(signSh)))
	want = append(want, goVerdict([]string{signShKey}, signSh, KindCore))

	got := runUboot(t, bin, cases)
	accepted := 0
	for i := range cases {
		g := got[i]
		if strings.HasPrefix(g, "err ") {
			g = "err"
		} else {
			accepted++
		}
		if g != want[i] {
			t.Errorf("%s:\nU-Boot %s\nGo     %s", cases[i], got[i], want[i])
		}
	}
	// The comparison means something only if both sides accept some of it.
	if accepted < 40 || want[len(want)-1] == "err" {
		t.Fatalf("only %d of %d cases verified", accepted, len(cases))
	}
}

// What the stick takes (ADR 0048): a core statement for this image's profile, signed by a
// release key, naming the file's SHA-256. Any SoundTap version goes in, older ones too: the
// gesture held at power-on is the confirmation. Nothing else does.
func TestUbootStickPolicy(t *testing.T) {
	bin := buildUbootVerifier(t)
	active, activePriv := testKey(t)
	reserve, reservePriv := testKey(t)
	_, strangerPriv := testKey(t)
	keys := hexKeys(t, active, reserve)
	pkg := sha256.Sum256([]byte("Update.stu"))
	other := sha256.Sum256([]byte("another Update.stu"))
	sign := func(priv ed25519.PrivateKey, kind, profile, version string) string {
		return mustSign(t, priv, Statement{Kind: kind, Profile: profile, Version: version, Digest: pkg[:]})
	}
	good := sign(activePriv, KindCore, ProfileProduction, "0.1.0")
	sig, _ := base64.StdEncoding.DecodeString(good[strings.Index(good, " sig=")+5:])
	sig[0] ^= 1
	badSig := good[:strings.Index(good, " sig=")+5] + base64.StdEncoding.EncodeToString(sig)

	var names, want, cases []string
	for _, c := range []struct {
		name, image, text string
		digest            [32]byte
		want              string
	}{
		{"good", ProfileProduction, good + "\n", pkg, "ok"},
		{"signed with the reserve key", ProfileProduction, sign(reservePriv, KindCore, ProfileProduction, "0.1.0"), pkg, "ok"},
		{"older version", ProfileProduction, sign(activePriv, KindCore, ProfileProduction, "0.0.1"), pkg, "ok"},
		{"newer version", ProfileProduction, sign(activePriv, KindCore, ProfileProduction, "9.0.0"), pkg, "ok"},
		{"production on an alpha image", ProfileAlpha, good, pkg, "ok"},
		{"alpha on an alpha image", ProfileAlpha, sign(activePriv, KindCore, ProfileAlpha, "0.1.0"), pkg, "ok"},
		{"wrong profile", ProfileProduction, sign(activePriv, KindCore, ProfileAlpha, "0.1.0"), pkg, stWrongProfile},
		{"an image of no known profile is production", "", sign(activePriv, KindCore, ProfileAlpha, "0.1.0"), pkg, stWrongProfile},
		{"wrong kind", ProfileProduction, sign(activePriv, KindApp, ProfileProduction, "0.1.0"), pkg, stWrongKind},
		{"signed for the way back to Bose", ProfileProduction, sign(activePriv, KindCore, ProfileProduction, StockVersion), pkg, stStock},
		{"bad signature", ProfileProduction, badSig, pkg, stBadSignature},
		{"signed by another key", ProfileProduction, sign(strangerPriv, KindCore, ProfileProduction, "0.1.0"), pkg, stBadSignature},
		{"edited after signing", ProfileProduction, strings.Replace(good, "version=0.1.0", "version=0.1.1", 1), pkg, stBadSignature},
		{"unsigned: an empty .sig", ProfileProduction, "", pkg, stNotStatement},
		{"unsigned: Bose's file renamed", ProfileProduction, "\x00\x00\x00\x01BOSE", pkg, stNotStatement},
		{"truncated signature", ProfileProduction, good[:len(good)-4], pkg, stBadEncoding},
		{"hash mismatch", ProfileProduction, good, other, stWrongFile},
	} {
		image := c.image
		if image == "" {
			image = "unknown"
		}
		names = append(names, c.name)
		want = append(want, c.want)
		cases = append(cases, fmt.Sprintf("stick %s %s %s %s", image, keys, hexText(c.text), hex.EncodeToString(c.digest[:])))
	}
	for i, got := range runUboot(t, bin, cases) {
		if got != want[i] {
			t.Errorf("%s: %s, want %s", names[i], got, want[i])
		}
	}
}
