// The USB-stick recovery in our U-Boot reads the same statement as soundtapd, from
// Update.stu.sig (ADR 0048), with a verifier in C: os/bootloader/uboot/soundtap-sig.c over
// TweetNaCl's ed25519. These tests build that code for the host, give it the statements Go
// signs and the ones a byte away from them, and require the same verdict as Verify; and
// they hold the keys U-Boot is built with to PublicKeys.

