// The ST20's U-Boot paints bootFrame(0) the moment the speaker gets power, long before
// soundtapd draws the same frame (os/bootloader/uboot/uboot-2026.07-st20-splash.patch).
// Regenerate the header after changing bootFrame: UPDATE_SPLASH=1 go test -run TestUbootSplash.
func TestUbootSplashIsBootFrame(t *testing.T) {
	t.Parallel()

	const path = "../../../os/bootloader/uboot/soundtap-splash.h"

	want := splashHeader(bootFrame(0))
	if os.Getenv("UPDATE_SPLASH") == "1" {
		err := os.WriteFile(path, want, 0o644)
		if err != nil {
			t.Fatal(err)
		}
	}

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale; regenerate it with UPDATE_SPLASH=1", path)
	}
}

// splashHeader packs a frame for the panel (two pixels per byte, even pixel in the low
// nibble, as oled.packFrame) and run-length encodes it as (count, byte) pairs.
func splashHeader(pix []byte) []byte {
	var buf bytes.Buffer
	buf.WriteString("/* Generated by app/cmd/soundtapd/display_splash_test.go from bootFrame(0). */\n")
	buf.WriteString("static const unsigned char soundtap_splash_rle[] = {")

	pairs := 0

	for pair := 0; pair < len(pix)/2; {
		packed := pix[2*pair]>>4 | pix[2*pair+1]&0xf0

		run := 1
		for run < 255 && pair+run < len(pix)/2 && pix[2*(pair+run)]>>4|pix[2*(pair+run)+1]&0xf0 == packed {
			run++
		}

		if pairs%8 == 0 {
			buf.WriteString("\n\t")
		} else {
			buf.WriteString(" ")
		}

		fmt.Fprintf(&buf, "%d, 0x%02x,", run, packed)

		pairs++
		pair += run
	}

	buf.WriteString("\n};\n")

	return buf.Bytes()
}
